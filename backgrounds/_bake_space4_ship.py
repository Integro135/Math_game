"""The starship's bake (the 🌌 scene, backgrounds/space4.bg.js) — renders the 3-D model in
backgrounds/space4_ship_bake.html and either shows it or writes the game's sprite sheet.

    python c:/Code/subtraction_game/backgrounds/_bake_space4_ship.py            # preview(s) → c:/tmp/space4/ship_*.png
    python c:/Code/subtraction_game/backgrounds/_bake_space4_ship.py bake       # → backgrounds/space4.ship.js (+ c:/tmp/space4/ship_sheet.png)

Edit PREVIEWS / BAKE below to look at something else (the command line stays the same).
A preview is the frame over a dark starry backdrop, as the game shows it."""
import base64, io, sys
from pathlib import Path
from playwright.sync_api import sync_playwright
from PIL import Image

try: sys.stdout.reconfigure(encoding="utf-8")
except Exception: pass

# ── CONFIG ──────────────────────────────────────────────────────────────────
# [name, {ppu (pixels per model unit), ss (samples per pixel side), yaw (degrees), mode (0 legs up · 1 legs alone · 2 legs down)}]
PREVIEWS = [
    ["cruise", {"ppu": 380, "ss": 2, "yaw": 15, "mode": 0}],
    ["yaw40", {"ppu": 190, "ss": 2, "yaw": 40, "mode": 0}],
    ["yaw65", {"ppu": 190, "ss": 2, "yaw": 65, "mode": 0}],
    ["yaw90", {"ppu": 190, "ss": 2, "yaw": 90, "mode": 0}],
    ["legs", {"ppu": 190, "ss": 2, "yaw": 15, "mode": 1}],
]
BAKE = {"ppu": 150, "ss": 4, "yaws": [15, 40, 65, 90], "q": 0.92}
# ────────────────────────────────────────────────────────────────────────────
BG_DIR = Path("c:/Code/subtraction_game/backgrounds")
OUT = Path("c:/tmp/space4"); OUT.mkdir(parents=True, exist_ok=True)
CHROME_EXE = "C:/Program Files/Google/Chrome/Application/chrome.exe"


def png_of(data_url):
    return Image.open(io.BytesIO(base64.b64decode(data_url.split(",", 1)[1]))).convert("RGBA")


def over_space(im):
    """the frame over a dark violet backdrop with a few stars — how it reads in the scene"""
    import random
    random.seed(7)
    bg = Image.new("RGBA", im.size, (16, 12, 40, 255))
    px = bg.load()
    for _ in range(im.size[0] * im.size[1] // 900):
        x, y = random.randrange(im.size[0]), random.randrange(im.size[1]); v = random.randrange(90, 230)
        px[x, y] = (v, v, min(255, v + 25), 255)
    bg.alpha_composite(im)
    return bg.convert("RGB")


with sync_playwright() as pw:
    browser = pw.chromium.launch(headless=True, executable_path=CHROME_EXE)
    page = browser.new_page()
    errors = []
    page.on("console", lambda m: errors.append(m.text) if m.type == "error" else None)
    page.on("pageerror", lambda e: errors.append(str(e)))
    page.goto((BG_DIR / "space4_ship_bake.html").as_uri())
    try:
        page.wait_for_function("window.shipReady === true", timeout=20000)
    except Exception:
        print("the studio did not start:", errors); browser.close(); raise SystemExit(1)
    if "bake" in sys.argv[1:]:
        r = page.evaluate("o => window.bakeShip(o)", BAKE)
        sheet = png_of(r["png"]); sheet.save(OUT / "ship_sheet.png"); over_space(sheet).save(OUT / "ship_sheet_view.png")
        meta = {k: r[k] for k in ("cw", "ch", "ppu", "yaws", "legs", "el", "cellW", "cellH")}
        js = ("/* space4.ship.js — GENERATED by backgrounds/_bake_space4_ship.py from the 3-D model in\n"
              "   backgrounds/space4_ship_bake.html. Do not edit: change the model there and bake again.\n"
              "   The 🌌 scene's starship as a sprite sheet: the ship at yaws " + ", ".join(f"{y}°" for y in r["yaws"]) + " (frames 0–" + str(len(r["yaws"]) - 1) + "),\n"
              "   then its landing legs alone (frame " + str(r["legs"]) + "). cw × ch = one frame in pixels, ppu = pixels per model\n"
              "   unit (the ship is 2 units long), el = the camera's elevation in degrees. Loaded by space4.bg.js. */\n"
              "(function(){window.SPACE4_SHIP={" + ",".join(f"{k}:{str(v).replace(' ', '')}" for k, v in meta.items()) + ",\n"
              "src:'" + r["src"] + "'};})();\n")
        (BG_DIR / "space4.ship.js").write_text(js, encoding="utf-8")
        print("baked:", meta, "| webp", len(r["src"]) // 1024, "KB (base64) | png", len(r["png"]) // 1024, "KB →", BG_DIR / "space4.ship.js")
    else:
        for name, o in PREVIEWS:
            im = png_of(page.evaluate("o => window.previewShip(o)", o))
            over_space(im).save(OUT / f"ship_{name}.png")
            print("preview:", OUT / f"ship_{name}.png", im.size)
    real = [e for e in errors if "font" not in e.lower()]
    print("errors:", real if real else "NONE")
    browser.close()
